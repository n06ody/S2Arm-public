"""Compare same-source synthetic DshVk and live-compiler graphics bindings.

Inputs are generated by the repository DshVk and DirectCompiler fixture builders;
they are original synthetic shader programs, never game-derived data.
"""
import collections
import base64
import json
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'android/tests'))
import host_link


def run(cmd):
    result = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, timeout=1200)
    if result.returncode:
        raise RuntimeError(f'{cmd[0]} rc={result.returncode}: {result.stdout.strip()} {result.stderr.strip()}')
    return result.stdout


def make_lib(dsh, target):
    stages = {}
    for file in dsh.glob('*_b.json'):
        doc = json.loads(file.read_text())
        if doc.get('stage') in ('vs', 'ps'):
            assert doc['stage'] not in stages
            stages[doc['stage']] = (doc['dm_ctl'], file.read_bytes(), file.with_suffix('.spv').read_bytes())
    assert set(stages) == {'vs', 'ps'}
    recs, shard = [], bytearray()
    for key, jb, spv in stages.values():
        for kind, payload in ((1, jb), (52, spv)):
            recs.append((int(key,16),kind,0,0,len(payload),len(shard)))
            shard.extend(payload)
    chain = re.search(r'#define DMSH_CHAIN "([0-9a-f]{12})"', (ROOT/'graphics/nvn/gfx/nvn/dmsh_chain.h').read_text()).group(1)
    idx = b'S2ALIB\0\0' + struct.pack('<IIII',1,len(recs),1,0) + chain.encode() + bytes(12)
    idx += struct.pack('<QQ',len(shard),0)
    idx += b''.join(struct.pack('<QBBHIQ',*r) for r in sorted(recs))
    target.mkdir(); (target/'lib.idx').write_bytes(idx); (target/'lib.000.pak').write_bytes(shard)
    return stages


def semantics(b):
    kind = b['kind']
    if kind == 'support': return ('program', kind)
    if kind == 'uniform': return (b['stage'],kind,b.get('slot',-1))
    if kind == 'storage': return (b['stage'],kind,b.get('nvnSlot',-1),b.get('rw'),b.get('cbSlot',-1),b.get('cbOffset',-1))
    if kind == 'texture': return (b['stage'],kind,b.get('slot',-1))
    return (b['stage'],kind)


def generate(tmp):
    cross = os.environ.get('SPIRV_CROSS') or shutil.which('spirv-cross')
    validator = shutil.which('spirv-val')
    if not cross:
        # Match the repository's DshVk test: compile the vendored CLI when no
        # installed SPIRV-Cross is available. All outputs stay in this worktree.
        src = ROOT/'graphics/third_party/spirv_cross'
        cross = tmp/'spirv-cross'
        names = ('main', 'spirv_cfg', 'spirv_cross', 'spirv_cross_parsed_ir',
                 'spirv_cross_util', 'spirv_glsl', 'spirv_hlsl', 'spirv_msl',
                 'spirv_parser', 'spirv_cpp', 'spirv_reflect')
        run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O1', '-o', cross,
             *(src/(name+'.cpp') for name in names)])
    if not validator:
        roots = [Path(p) for p in (os.environ.get('ANDROID_NDK_ROOT'), os.environ.get('ANDROID_NDK_HOME')) if p]
        roots += list((Path(os.environ.get('ANDROID_HOME', '/nonexistent'))/'ndk').glob('*'))
        roots += list(Path('/opt/android-sdk/ndk').glob('*'))
        for root in roots:
            for host in ('darwin-x86_64', 'linux-x86_64'):
                candidate = root/'shader-tools'/host/'spirv-val'
                if candidate.is_file() and os.access(candidate, os.X_OK):
                    validator = str(candidate)
                    break
            if validator:
                break
    if not validator:
        raise RuntimeError('spirv-val is required (SPIRV-Tools or NDK shader-tools)')
    lib = ROOT / ('build/dsx/libdsx.dylib' if sys.platform == 'darwin' else 'build/dsx/linux/libdsx.so')
    run(['make', '-s', '-C', ROOT/'graphics/dsx', lib])
    projects = [
        ('fixture', ROOT/'android/tests/libpack_fixture/LibpackFixture.csproj', 'LibpackFixture'),
        ('requests', ROOT/'graphics/tools/direct/tests/compiler/DirectCompiler.Tests.csproj', 'S2A.DirectCompiler.Tests'),
        ('cli', ROOT/'graphics/tools/direct/compiler/cli/S2A.DirectCompiler.Cli.csproj', 'S2A.DirectCompiler.Cli'),
    ]
    dlls = {}
    for name, project, assembly in projects:
        artifacts = tmp/(name+'-art')
        run(['dotnet', 'build', project, '-c', 'Release', '-p:ArtifactsPath='+str(artifacts), '--nologo'])
        dlls[name] = Path(run(['dotnet', 'msbuild', project, '-p:Configuration=Release',
                               '-p:ArtifactsPath='+str(artifacts), '-nologo', '-getProperty:TargetPath']).strip())
        assert dlls[name].name == assembly+'.dll'
    fixture = tmp/'fixture'
    run(['dotnet', dlls['fixture'], cross, lib, fixture])
    for spv in (fixture/'out').glob('*.spv'):
        run([validator, '--target-env', 'vulkan1.1', spv])
    requests = tmp/'requests'
    run(['dotnet', dlls['requests'], '--emit-requests', requests])
    request = json.loads((requests/'c2tex.json').read_text())
    request['program']['textures'][0]['handle'] = 8
    for stage in request['program']['stages']:
        st = 'vs' if stage['stage'] == 'vs' else 'ps'
        for field, ext in (('code','code'), ('control','ctl'), ('c1','c1')):
            stage[field] = base64.b64encode((fixture/(st+'.'+ext)).read_bytes()).decode()
        stage['constantBufferUse'] = 11 if st == 'vs' else 8
    request_path = tmp/'request.json'
    request_path.write_text(json.dumps(request))
    online_dir = tmp/'online'
    run(['dotnet', dlls['cli'], 'compile', '--request', request_path, '--output', online_dir])
    return fixture/'out', online_dir/'program.json'


def main():
    if len(sys.argv) not in (1, 3):
        raise SystemExit('usage: libpack_graphics_compare_test.py [<synthetic-dsh-out> <synthetic-online-program.json>]')
    build = ROOT/'build'; build.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='libpack-comparison-',dir=build) as td:
        tmp=Path(td)
        dsh, online_path = map(Path,sys.argv[1:]) if len(sys.argv) == 3 else generate(tmp)
        stages=make_lib(dsh,tmp/'lib')
        exe=tmp/'probe'
        cmd=['cc','-std=c11','-D_GNU_SOURCE','-Wall','-Wextra','-Werror',
             '-I'+str(ROOT/'android/native'),'-I'+str(ROOT/'android/native/direct'),'-I'+str(ROOT/'android/native/nvn'),
             '-o',str(exe),str(ROOT/'android/tests/libpack_graphics_compare_probe.c')]
        cmd += [str(ROOT/'android/native/direct'/p) for p in ('libpack_vk.c','jv.c','json.c')]
        cmd += [str(ROOT/'android/native/nvn/nvn_vk_program_result.c')]
        host_link.run(cmd,check=True,timeout=120)
        generated=json.loads(run([exe,tmp/'lib',stages['vs'][0],stages['ps'][0]]))
        offline=generated['program']['content']['bindings']
        online_content=json.loads(online_path.read_text())['content']
        online=online_content['bindings']
        # SPIRV-Cross reports only compiler-emitted descriptor variables. Binding coordinates
        # are intentionally compared to the SPIR-V of their own path (DshVk remaps them).
        reflected={}
        support_count=0
        for stage in ('vs','ps'):
            spv=tmp/(stage+'.spv'); spv.write_bytes(stages[stage][2])
            data=json.loads(run(['spirv-cross',spv,'--reflect']))
            for typ in ('ubos','ssbos','textures','images','separate_images','separate_samplers'):
                for d in data.get(typ,[]):
                    key=(d['set'],d['binding'])
                    assert key not in reflected, ('duplicate offline descriptor',key)
                    reflected[key]=(stage,typ,d['name'])
                    if d['name']=='support_buffer': support_count+=1
        actual_coordinates=collections.Counter((b['set'],b['binding']) for b in offline)
        if actual_coordinates != collections.Counter(reflected.keys()):
            print('FAIL SPIR-V descriptor coordinates: missing',list((collections.Counter(reflected.keys())-actual_coordinates).elements()),
                  'extra',list((actual_coordinates-collections.Counter(reflected.keys())).elements()),flush=True)
            raise SystemExit(1)
        type_map={'ubos': ('uniform','support'), 'ssbos': ('storage',),
                  'textures': ('texture',), 'images': ('image',)}
        for b in offline:
            stage, typ, name = reflected[(b['set'], b['binding'])]
            assert b['kind'] in type_map.get(typ, ()), ('offline descriptor type mismatch',name,b)
            assert b['stage'] == ('program' if name == 'support_buffer' else ('fs' if stage == 'ps' else stage)), (name,b)
        if len(sys.argv) == 1:
            names = {entry[2] for entry in reflected.values()}
            metal_kinds = {b['kind'] for _, jb, _ in stages.values() for b in json.loads(jb)['bindings']}
            assert 'vp_c1' in names, ('same-source fixture must exercise c1 descriptor', names, metal_kinds)
            assert ('vs','uniform',1) in [semantics(b) for b in online], 'live c1 slot must be present'
        # Live allocator coordinates are different after DshVk remapping: check
        # them against the live SPIR-V, never against the offline numbers.
        live_reflected = []
        for stage in online_content['stages']:
            path=tmp/('live-'+stage['stage']+'.spv')
            path.write_bytes(base64.b64decode(stage['spirv'], validate=True))
            data=json.loads(run(['spirv-cross',path,'--reflect']))
            for typ in ('ubos','ssbos','textures','images'):
                for d in data.get(typ,[]): live_reflected.append((stage['stage'],typ,d))
        for stage,typ,d in live_reflected:
            matches=[b for b in online if b['set']==d['set'] and b['binding']==d['binding']
                     and b['stage'] in (stage,'program') and b['kind'] in type_map[typ]]
            assert len(matches)==1, ('live SPIR-V descriptor mismatch', stage, d['name'])
        expected=[semantics(b) for b in online]
        expected += [('program','support')]*(support_count-1)
        actual=[semantics(b) for b in offline]
        if collections.Counter(expected) != collections.Counter(actual):
            print('FAIL producer semantic bindings: expected',expected,'actual',actual,flush=True)
            raise SystemExit(1)
        required=online_content['supportLayout']['requiredSize']
        if generated['parsedSupportBytes'] != required:
            print('FAIL support requiredSize: live',required,'offline parser',generated['parsedSupportBytes'],flush=True)
            raise SystemExit(1)
        for stage in ('vs','ps'):
            spv=tmp/(stage+'.spv')
            data=json.loads(run(['spirv-cross',spv,'--reflect']))
            for ubo in data.get('ubos',[]):
                if ubo['name']=='support_buffer':
                    assert generated['parsedSupportBytes'] >= ubo['block_size'], ('support buffer too small',stage)
        print('PASS same-source compiler semantics,',len(offline),'offline descriptors,',len(online),'live descriptors')


if __name__ == '__main__': main()
