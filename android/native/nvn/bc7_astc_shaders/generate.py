"""Generate Q48 endpoint tables and the Vulkan 1.1 BC7 encoder."""
import argparse
from pathlib import Path
import re
import struct
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
ASTCENC = HERE.parents[3] / "graphics/third_party/astc-encoder"


def read_table(file, name, length):
    source = (ASTCENC / file).read_text()
    body = re.search(r"\b" + name + r"(?:\[\d+\])+\s*\{(.*?)\};", source, re.S)[1]
    values = [int(word) for word in re.findall(r"\b\d+\b", body)]
    assert len(values) == length, name
    return values


def rows(values, width, render=str):
    return ["    " + ", ".join(render(n) for n in values[i:i + width]) + ","
            for i in range(0, len(values), width)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tables-only", action="store_true")
    args = parser.parse_args()

    q48 = read_table("astcenc_quantization.cpp", "color_scrambled_pquant_to_uquant_q48", 48)
    trits = read_table("astcenc_integer_sequence.cpp", "integer_of_trits", 243)
    closest = [min(range(48), key=lambda i: (abs(q48[i] - val), q48[i])) for val in range(256)]
    args.out.mkdir(exist_ok=True, parents=True)

    def emit(path, lines):
        content = "\n".join(["// SPDX-License-Identifier: Apache-2.0",
                             "// Generated by bc7_astc_shaders/generate.py. Tables from Arm astcenc.",
                             *lines, ""])
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"{path}: stale generated file")
        else:
            path.write_text(content)

    emit(HERE / "alpha_q48.h", [
        "#pragma once", "#include <stdint.h>",
        "static const uint8_t nvk_bc7_alpha_q48[256] = {",
        *rows([q48[i] for i in closest], 16), "};",
    ])
    with tempfile.TemporaryDirectory(dir=args.out) as temp:
        temp = Path(temp)
        # Store two endpoint symbols per word and four trit encodings per word.
        # A symbol carries both the BISE code and decoded value used for RGB ordering.
        symbols = [(q48[i] << 8) | i for i in closest]
        words = [symbols[i] | (symbols[i + 1] << 16) for i in range(0, 256, 2)]
        padded = trits + [0]
        packed_trits = [sum(padded[i + j] << (8 * j) for j in range(4)) for i in range(0, len(padded), 4)]
        table = []
        for name, array in [("q48", words), ("trits", packed_trits)]:
            table.append(f"const uint {name}[{len(array)}] = uint[](")
            table.extend(rows(array, 8, lambda n: f"0x{n:08x}u"))
            table[-1] = table[-1].rstrip(",")
            table.append(");")
        tables = args.out / "encoding_tables.glsl"
        tables.write_text("\n".join(table) + "\n")
        if args.tables_only:
            return
        spirv = temp / "encode.spv"
        subprocess.run([args.glslc, "--target-env=vulkan1.1", "-O", "-I", str(args.out),
                        str(HERE / "encode.comp"), "-o", str(spirv)], check=True)
        words = [word for (word,) in struct.iter_unpack("<I", spirv.read_bytes())]
        emit(HERE.parent / "backend_vulkan_bc7_astc_spv.h", [
            "#pragma once", "#include <stdint.h>", "static const uint32_t nvk_bc7_astc_spv[] = {",
            *rows(words, 8, lambda n: f"0x{n:08x}u"), "};",
        ])


if __name__ == "__main__":
    main()
