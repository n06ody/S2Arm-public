import argparse
from pathlib import Path
import subprocess
import tempfile

here = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--glslc', default='glslc')
a = parser.parse_args()
with tempfile.TemporaryDirectory(dir=here.parents[3]/'build') as tmp:
    out = Path(tmp)/'deswizzle.spv'
    subprocess.run([a.glslc, '--target-env=vulkan1.1', '-O', str(here/'deswizzle.comp'), '-o', str(out)], check=True)
    b = out.read_bytes()
    if len(b) % 4: raise ValueError('SPIR-V not word aligned')
    words = [int.from_bytes(b[i:i+4], 'little') for i in range(0, len(b), 4)]
    lines = ['// SPDX-License-Identifier: Apache-2.0', '// Generated by deswizzle_shaders/generate.py (Vulkan 1.1).', '#pragma once', '#include <stdint.h>', 'static const uint32_t nvk_deswizzle_spv[] = {']
    lines += ['    ' + ', '.join('0x%08xu' % w for w in words[i:i+8]) + ',' for i in range(0, len(words), 8)]
    lines += ['};', '']
    (here.parent/'backend_vulkan_deswizzle_spv.h').write_text('\n'.join(lines))
