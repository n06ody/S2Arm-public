import argparse
from pathlib import Path
import subprocess
import tempfile

here = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--glslc', default='glslc')
parser.add_argument('--word', action='store_true', help='生成四字节对齐字读专用模块')
a = parser.parse_args()
name = 'deswizzle_word' if a.word else 'deswizzle'
defines = ['-DS2A_DESWIZZLE_WORD=1'] if a.word else []
with tempfile.TemporaryDirectory(dir=here.parents[3]/'build') as tmp:
    out = Path(tmp)/f'{name}.spv'
    subprocess.run([a.glslc, '--target-env=vulkan1.1', '-O', *defines, str(here/'deswizzle.comp'), '-o', str(out)], check=True)
    b = out.read_bytes()
    if len(b) % 4: raise ValueError('SPIR-V not word aligned')
    words = [int.from_bytes(b[i:i+4], 'little') for i in range(0, len(b), 4)]
    lines = ['// SPDX-License-Identifier: Apache-2.0', '// Generated by deswizzle_shaders/generate.py (Vulkan 1.1).', '#pragma once', '#include <stdint.h>', f'static const uint32_t nvk_{name}_spv[] = {{']
    lines += ['    ' + ', '.join('0x%08xu' % w for w in words[i:i+8]) + ',' for i in range(0, len(words), 8)]
    lines += ['};', '']
    (here.parent/f'backend_vulkan_{name}_spv.h').write_text('\n'.join(lines))
