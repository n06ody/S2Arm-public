"""Generate the Vulkan 1.1 BC1-to-ASTC compute shader header."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument("--glslc", default="glslc")
args = parser.parse_args()
build = HERE.parents[3] / "build"
build.mkdir(exist_ok=True)
with tempfile.TemporaryDirectory(dir=build) as temp:
    binary = Path(temp) / "encode.spv"
    subprocess.run(
        [args.glslc, "--target-env=vulkan1.1", "-O", str(HERE / "encode.comp"), "-o", str(binary)],
        check=True,
    )
    words = [word for (word,) in struct.iter_unpack("<I", binary.read_bytes())]

lines = [
    "// SPDX-License-Identifier: Apache-2.0",
    "// Generated by bc1_astc_shaders/generate.py (Vulkan 1.1).",
    "#pragma once",
    "#include <stdint.h>",
    "static const uint32_t nvk_bc1_astc_spv[] = {",
]
for i in range(0, len(words), 8):
    lines.append("    " + ", ".join(f"0x{word:08x}u" for word in words[i:i + 8]) + ",")
lines += ["};", ""]
(HERE.parent / "backend_vulkan_bc1_astc_spv.h").write_text("\n".join(lines))
