// 调试：debug.s2a.stderr=<path> 时把 stderr 落盘，用于抓 AOT fail-fast 首行。
static void s2a_redirect_stderr_once() {
    static bool done = false;
    if (done) return;
    done = true;
    char p[PROP_VALUE_MAX] = {0};
    if (__system_property_get("debug.s2a.stderr", p) > 0 && p[0]) {
        int fd = open(p, O_WRONLY | O_CREAT | O_APPEND, 0666);
        if (fd >= 0) dup2(fd, 2);
    }
}
