            host->asset_paths.emplace(name + ".fixups.tsv", root + "/" + fix);
            host->asset_paths.emplace(name + ".gates.tsv", root + "/" + gate);
            if (!wide.empty()) host->asset_paths.emplace(name + ".widen.tsv", root + "/" + wide);
            host->module_names.push_back(name);
