static JNIEnv *capprobe_attach(bool *attached) {
    *attached = false;
    JavaVM *vm = g_vm;
    if (!vm) return nullptr;
    JNIEnv *env = nullptr;
    if (vm->GetEnv(reinterpret_cast<void **>(&env), JNI_VERSION_1_6) != JNI_OK) {
        if (vm->AttachCurrentThread(&env, nullptr) != JNI_OK) return nullptr;
        *attached = true;
    }
    return env;
}

extern "C" __attribute__((visibility("default"))) int s2a_capprobe_ensure(void) {
    if (g_capprobe_dir.empty()) return 0;   // 未配置（诊断构建/外壳未传目录）：探测跳过，能力位读无文件→假
    bool attached;
    JNIEnv *env = capprobe_attach(&attached);
    if (!env) return 0;
    jclass cls = g_capprobe_cls;
    if (!cls) fprintf(stderr, "S2Arm capprobe: CapProbe class unresolved at configure; probe skipped\n");
    jmethodID mid = cls ? env->GetStaticMethodID(cls, "ensure",
        "(Ljava/lang/String;Ljava/lang/String;Ljava/lang/String;)V") : nullptr;
    if (cls && mid) {
        jstring dir = env->NewStringUTF(g_capprobe_dir.c_str());
        jstring badlist = env->NewStringUTF(g_capprobe_badlist.c_str());
        jstring appver = env->NewStringUTF(g_capprobe_appver.c_str());
        env->CallStaticVoidMethod(cls, mid, dir, badlist, appver);
    }
    if (env->ExceptionCheck()) { env->ExceptionDescribe(); env->ExceptionClear(); }
    if (attached) g_vm->DetachCurrentThread();
    return 0;
}

extern "C" __attribute__((visibility("default"))) void s2a_capprobe_runtime_lost(void) {
    const char *path = getenv("S2A_CAPPROBE_RESULT");
    if (!path || !*path) return;
    bool attached;
    JNIEnv *env = capprobe_attach(&attached);
    if (!env) return;
    jclass cls = g_capprobe_cls;
    jmethodID mid = cls ? env->GetStaticMethodID(cls, "markRuntimeLost",
        "(Ljava/lang/String;)V") : nullptr;
    if (cls && mid) {
        jstring jpath = env->NewStringUTF(path);
        env->CallStaticVoidMethod(cls, mid, jpath);
    }
    if (env->ExceptionCheck()) { env->ExceptionDescribe(); env->ExceptionClear(); }
    if (attached) g_vm->DetachCurrentThread();
}

