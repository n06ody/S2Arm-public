// Single-library build: the service layer is linked into this library, so its native
// imports resolve at link time and its exports are plain calls.
static std::string cs_runtime() {
    auto start = std::chrono::steady_clock::now();
    long rss = rss_kib();
    s2a_android_set_screen_w(2400);
    char out[512];
    int failures = s2a_android_cs_selftest(out, sizeof out);
    long long first = ms_since(start);
    bool width = strstr(out, "s2a_screen_w=2400") != nullptr;
    bool mark = !strcmp(s2a_android_last_boot_mark(), "cs-selftest");
    s2a_ap_audio_mark();   // a service-layer method
    // C++ exceptions use the NDK's libunwind, the runtime's copy being renamed (cs/build.sh).
    bool cxx = false;
    try { throw std::runtime_error("selftest"); } catch (const std::runtime_error &) { cxx = true; }
    bool ok = !failures && width && mark && cxx;
    return "C# diagnostic link (NativeAOT static, native providers are stubs, S2A_Init not executed): " + std::string(ok ? "ok" : "FAILED")
        + "; runtime started + first call " + std::to_string(first) + " ms, RSS +" + std::to_string((rss_kib() - rss) >> 10)
        + " MiB; C#->C value " + (width ? "ok" : "WRONG") + ", C#->C string " + (mark ? "ok" : "WRONG")
        + ", C++ exception " + (cxx ? "ok" : "FAILED") + "; " + out + "\n" + audio_selftest() + "\n" + codec_selftest();
}
#else
// NativeAOT libraries from cs/build.sh, loaded the way the service layer will be. A
// NativeAOT runtime cannot be unloaded and a process holds only one, so the handle is
// never closed and only one library is loaded: the service composition when the APK
// carries it (S2ARM_ANDROID_CS_SERVICES=1), otherwise the probe.
static std::string cs_runtime() {
    auto start = std::chrono::steady_clock::now();
    long rss = rss_kib();
    if (void *svc = dlopen("libs2a_cs.so", RTLD_NOW | RTLD_LOCAL)) {
        long long load = ms_since(start);
        auto mark = reinterpret_cast<void (*)()>(dlsym(svc, "s2a_ap_audio_mark"));
        if (!mark || !dlsym(svc, "S2A_Init")) return "C# services: S2A_Init / s2a_ap_audio_mark not exported";
        mark();   // first managed call: starts the runtime and runs a service-layer method
        return "C# services diagnostic (S2A_Init export found, not executed): loaded in " + std::to_string(load)
            + " ms, runtime started + first call in " + std::to_string(ms_since(start) - load) + " ms, RSS +"
            + std::to_string((rss_kib() - rss) >> 10) + " MiB";
    }
    void *lib = dlopen("libs2a_cs_probe.so", RTLD_NOW | RTLD_LOCAL);
    if (!lib) return std::string("C# NativeAOT: not loaded (") + dlerror() + ")";
    auto run = reinterpret_cast<int (*)(char *, int)>(dlsym(lib, "s2a_cs_probe"));
    auto lookup = reinterpret_cast<int (*)(const char *)>(dlsym(lib, "s2a_cs_lookup"));
    if (!run || !lookup) return "C# NativeAOT: probe exports missing";
    char out[1024];
    int failures = run(out, sizeof out);
    std::string r = "C# NativeAOT (linux-bionic-arm64): " + std::string(failures ? std::to_string(failures) + " FAILED" : "ok")
        + ", " + std::to_string(ms_since(start)) + " ms incl. load; " + out;
    // Host exports as seen from C# through the main program handle, before and after
    // promoting this library to RTLD_GLOBAL.
    int before = lookup("s2a_vpad_read");
    void *self = self_handle(RTLD_NOW | RTLD_GLOBAL);
    int after = lookup("s2a_vpad_read");
    return r + "\nC# main-program lookup of s2a_vpad_read: " + (before ? "found" : "not found")
        + "; after RTLD_GLOBAL " + (self ? "" : "(promotion failed) ") + (after ? "found" : "not found");
}
#endif
#endif // 诊断自测不会链接或启动于真实游戏组合。

