// This library's file as the dynamic linker recorded it: an entry of the APK (base.apk!/lib/...)
// or, for a debuggable build's development override (RuntimeLibrary.java), its verified copy in the code cache.
static const char *self_path() {
    Dl_info info{};
    return dladdr(reinterpret_cast<void *>(&self_path), &info) ? info.dli_fname : nullptr;
}

#if defined(S2A_ANDROID_GAME_RUNTIME) || !defined(S2A_CS_STATIC)
// This very library's handle (RTLD_NOLOAD: never a second copy). The APK's library, loaded from inside
// the APK (base.apk!/lib/...), keeps the soname lookup it always used; a development override loaded with
// System.load from another file takes its handle by its own recorded path, not by soname.
static void *self_handle(int flags) {
    const char *path = self_path();
    bool override = path && !std::strstr(path, ".apk!/");
    return dlopen(override ? path : "libs2arm_android.so", flags | RTLD_NOLOAD);
}
#endif

