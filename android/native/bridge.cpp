static char g_exitlog_path[PROP_VALUE_MAX];
struct s2a_unwind { void *p[48]; int n; };
static _Unwind_Reason_Code s2a_unwind_cb(struct _Unwind_Context *ctx, void *arg) {
    struct s2a_unwind *u = (struct s2a_unwind *)arg;
    if (u->n < 48) u->p[u->n++] = (void *)_Unwind_GetIP(ctx);
    return _URC_NO_REASON;
}
static void s2a_log_exit(const char *why, int code) {
    if (!g_exitlog_path[0]) return;
    int fd = open(g_exitlog_path, O_WRONLY | O_CREAT | O_TRUNC, 0666);
    if (fd < 0) return;
    // 先写“谁、什么码”这一行：后面 _Unwind_Backtrace 崩掉也不会把这条信息埋掉。
    {
        char head[160];
        int hl = snprintf(head, sizeof head, "%s(%d): entered exit logger\n", why, code);
        if (hl > (int)sizeof head - 1) hl = (int)sizeof head - 1;   // snprintf 返回“应写长度”，不能直接当写长度
        if (hl > 0) (void)!write(fd, head, (size_t)hl);
    }
    {
        int m = open("/proc/self/maps", O_RDONLY);
        if (m >= 0) {
            char mb[512]; ssize_t r;
            while ((r = read(m, mb, sizeof mb)) > 0) (void)!write(fd, mb, (size_t)r);
            close(m);
        }
    }
    struct s2a_unwind u; memset(&u, 0, sizeof u);
    _Unwind_Backtrace(s2a_unwind_cb, &u);
    char buf[512];
    int len = snprintf(buf, sizeof buf, "%s(%d): %d frames\n", why, code, u.n);
    if (len > (int)sizeof buf - 1) len = (int)sizeof buf - 1;
    if (len > 0) (void)!write(fd, buf, (size_t)len);
    for (int i = 0; i < u.n; i++) {
        // dladdr 只依赖动态符号表：即使 so 被 strip，也能看出这一帧属于哪个模块
        // （我们的 libs2arm_android.so / libart.so / libc.so / 驱动），从而判断是谁调的 exit。
        Dl_info di;
        const char *mod = "?", *sym = "?";
        if (dladdr(u.p[i], &di) && di.dli_fname) {
            mod = di.dli_fname;
            if (di.dli_sname) sym = di.dli_sname;
        }
        len = snprintf(buf, sizeof buf, "#%02d %p %s %s\n", i, u.p[i], sym, mod);
        if (len > (int)sizeof buf - 1) len = (int)sizeof buf - 1;   // dladdr 的模块/符号名可能很长
        if (len > 0) (void)!write(fd, buf, (size_t)len);
    }
    nvn_vk_callring_dump(fd);   // 最近的关键 Vulkan 调用（debug.s2a.callring=1 时才有内容）
    close(fd);
}
static void s2a_exit_probe(void) { s2a_log_exit("atexit", 0); }
// 链接期 --wrap：AOT 静态库里的 exit/_exit 引用被改到这里，先落盘再转真函数。
extern "C" void __real__exit(int);
extern "C" void __real_exit(int);
extern "C" void __wrap__exit(int code) { s2a_log_exit("_exit", code); __real__exit(code); }
extern "C" void __wrap_exit(int code) { s2a_log_exit("exit", code); __real_exit(code); }

// JNI 装载即重定向 stderr（debug.s2a.stderr）并注册 exit 探针（debug.s2a.exitlog），
// 早于任何 Java/游戏逻辑。exit() 会触发 atexit；_exit()/abort() 不会。
extern "C" int JNI_OnLoad(JavaVM *vm, void *reserved) {
    (void)vm; (void)reserved;
    s2a_redirect_stderr_once();
    __system_property_get("debug.s2a.exitlog", g_exitlog_path);
    if (g_exitlog_path[0]) atexit(s2a_exit_probe);
    return 0x00010006;   // JNI_VERSION_1_6
}
