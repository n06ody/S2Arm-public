static bool safe_asset_path(const std::string &path) {
    if (path.empty() || path.front() == '/' || path.back() == '/' || path.find('\\') != std::string::npos) return false;
    for (size_t at = 0; at < path.size();) {
        size_t end = path.find('/', at);
        if (end == std::string::npos) end = path.size();
        std::string part = path.substr(at, end - at);
        if (part.empty() || part == "." || part == "..") return false;
        for (unsigned char c : part) if (c < 32 || c == 127) return false;
        at = end + 1;
    }
    return true;
}

// Runs on the loader worker. Hash the exact stable memory offered to the existing loader.
static bool verify_game_bytes(const std::string &path, const void *bytes, size_t length) {
    if (!g_vm || !g_bridge || length > static_cast<size_t>(INT64_MAX)) return false;
    JNIEnv *env = nullptr;
    bool attached = false;
    if (g_vm->GetEnv(reinterpret_cast<void **>(&env), JNI_VERSION_1_6) != JNI_OK) {
        if (g_vm->AttachCurrentThread(&env, nullptr) != JNI_OK) return false;
        attached = true;
    }
    jmethodID method = env->GetStaticMethodID(g_bridge, "verifyGameBytes", "(Ljava/lang/String;Ljava/nio/ByteBuffer;)Z");
    jstring name = env->NewStringUTF(path.c_str());
    jobject buffer = env->NewDirectByteBuffer(const_cast<void *>(bytes), static_cast<jlong>(length));
    bool ok = method && name && buffer && !env->ExceptionCheck()
        && env->CallStaticBooleanMethod(g_bridge, method, name, buffer) == JNI_TRUE;
    if (env->ExceptionCheck()) { env->ExceptionClear(); ok = false; }
    if (buffer) env->DeleteLocalRef(buffer);
    if (name) env->DeleteLocalRef(name);
    if (attached) g_vm->DetachCurrentThread();
    if (!ok) __android_log_print(ANDROID_LOG_ERROR, "S2Arm", "Game source integrity failed: %s", path.c_str());
    return ok;
}

// A missing optional policy is harmless only when admission also says it was absent.
static int missing_policy_error(const std::string &path) {
    if (!g_vm || !g_bridge) return EIO;
    JNIEnv *env = nullptr; bool attached = false;
    if (g_vm->GetEnv(reinterpret_cast<void **>(&env), JNI_VERSION_1_6) != JNI_OK) {
        if (g_vm->AttachCurrentThread(&env, nullptr) != JNI_OK) return EIO;
        attached = true;
    }
    jmethodID method = env->GetStaticMethodID(g_bridge, "gameFileAdmission", "(Ljava/lang/String;)I");
    jstring name = env->NewStringUTF(path.c_str());
    jint status = method && name && !env->ExceptionCheck() ? env->CallStaticIntMethod(g_bridge, method, name) : -1;
    if (env->ExceptionCheck()) { env->ExceptionClear(); status = -1; }
    if (name) env->DeleteLocalRef(name);
    if (attached) g_vm->DetachCurrentThread();
    return status == 0 ? ENOENT : EIO;
}

static bool optional_widen_policy(const char *name) {
    static const char *const names[] = {"widen_enable.handheld.tsv", "widen_enable.docked.tsv", "widen_full.handheld.tsv", "widen_full.docked.tsv", "widen_verified.tsv"};
    for (const char *candidate : names) if (!strcmp(name, candidate)) return true;
    return false;
}

static int read_game_asset(void *context, const char *filename, s2a_loader_blob *out) {
    auto *host = static_cast<AndroidHost *>(context);
    if (!filename || !out) return EINVAL;
    *out = {};
    auto found = host->asset_paths.find(filename);
    if (found == host->asset_paths.end()) return ENOENT;
    if (host->asset_root.empty()) {
        // Copy first: path replacement or later same-inode writes cannot change the verified
        // memory consumed by the loader. GameStorage remains the cooperating-writer lease.
        FILE *file = fopen(found->second.c_str(), "rb");
        if (!file) {
            if (errno != ENOENT) return errno;
            return optional_widen_policy(filename) ? missing_policy_error(found->second) : EIO;
        }
        if (fseeko(file, 0, SEEK_END) != 0) { fclose(file); return EIO; }
        off_t length = ftello(file);
        if (length < 0 || static_cast<uint64_t>(length) > SIZE_MAX || fseeko(file, 0, SEEK_SET) != 0) {
            fclose(file); return EIO;
        }
        void *bytes = malloc(length ? static_cast<size_t>(length) : 1);
        if (!bytes) { fclose(file); return ENOMEM; }
        bool ok = fread(bytes, 1, static_cast<size_t>(length), file) == static_cast<size_t>(length) && !ferror(file);
        fclose(file);
        if (!ok || !verify_game_bytes(found->second, bytes, static_cast<size_t>(length))) { free(bytes); return EIO; }
        out->bytes = bytes; out->length = static_cast<size_t>(length); out->lease = bytes;
        return 0;
    }
    AAsset *asset = AAssetManager_open(host->assets, found->second.c_str(), AASSET_MODE_BUFFER);
    if (!asset) return optional_widen_policy(filename) ? missing_policy_error(found->second) : EIO;
    off64_t length = AAsset_getLength64(asset);
    const void *bytes = AAsset_getBuffer(asset);
    if (length < 0 || (length && !bytes) || !verify_game_bytes(found->second, bytes, static_cast<size_t>(length))) {
        AAsset_close(asset); return EIO;
    }
    out->bytes = bytes;
    out->length = static_cast<size_t>(length);
    out->lease = asset;
    return 0;
}

static void release_game_asset(void *context, s2a_loader_blob *blob) {
    auto *host = static_cast<AndroidHost *>(context);
    if (blob && blob->lease) {
        if (host->asset_root.empty()) free(blob->lease);
        else AAsset_close(static_cast<AAsset *>(blob->lease));
    }
    if (blob) *blob = {};
}

static void *run_game(void *context) {
    auto *host = static_cast<AndroidHost *>(context);
    pthread_setname_np(pthread_self(), "s2arm-start");
    int rc = s2a_android_runtime_run_v2(&host->request);
    host->run_returned.store(true);
    __android_log_print(ANDROID_LOG_ERROR, "S2Arm", "Game runtime returned: %d; ending this process", rc);
    // 只有启动 worker 才能在装载/初始化失败后收尾，不能与仍在修改模块表的 loader 并发。
    s2a_host_shutdown("game runtime returned");
    return nullptr;
}

static void *stop_game(void *context) {
    auto *host = static_cast<AndroidHost *>(context);
    pthread_setname_np(pthread_self(), "s2arm-stop");
    if (host->cooperative_exit.load()) {
        // 正式 Applet Exit 已送达：等客体自己收尾到 nnMain 返回。启动 worker 在客体停稳后
        // 接管 s2a_host_shutdown，这是唯一「客体已停、驱动可以安全清场」的路径。
        // 窗口必须覆盖 Surface 生命周期（Activity 已改为不在原生收尾前 finish）。
        auto cooperative_deadline = std::chrono::steady_clock::now() + std::chrono::milliseconds(1200);
        while (std::chrono::steady_clock::now() < cooperative_deadline) {
            if (host->run_returned.load()) return nullptr;   // 启动 worker 已转交 shared shutdown
            usleep(5000);
        }
        __android_log_print(ANDROID_LOG_WARN, "S2Arm", "Applet Exit deadline expired; guest still running, forcing stop");
        const s2a_host_api_v1 *api = s2a_host_get();
        if (api && api->stop) api->stop->request_stop(api->host, S2A_HOST_STOP_USER, host->stop_reason.c_str());
        s2a_android_runtime_request_stop(1);
    }
    if (!host->launch_accepted.load()) {
        s2a_host_shutdown(host->stop_reason.c_str());
        return nullptr;
    }
    // 正常收局先清 attempt 锁：s2a_host_shutdown 在共享生命周期里以 _exit(0) 结束进程，
    // 不会返回到 s2a_android_runtime_run_v2 的 s2a_direct_finish；不在这里清，锁会留给下一局，
    // AUTO 就会以 "previous direct attempt did not end normally" 退回 generic（真机复现）。
    __android_log_print(ANDROID_LOG_INFO, "S2Arm", "stop_game: launch=%d normal=%d returned=%d reason=%s",
                        (int)host->launch_accepted.load(), (int)host->stop_normal.load(),
                        (int)host->run_returned.load(), host->stop_reason.c_str());
    if (host->stop_normal.load()) {
        int32_t frc = s2a_direct_finish(1);
        __android_log_print(ANDROID_LOG_INFO, "S2Arm", "stop_game: direct finish rc=%d", (int)frc);
    }
    auto deadline = std::chrono::steady_clock::now() + std::chrono::milliseconds(1500);
    while (std::chrono::steady_clock::now() < deadline) {
        if (host->run_returned.load()) return nullptr;   // 启动 worker 已转交 shared shutdown。
        struct s2a_android_runtime_status status{};
        if (s2a_android_runtime_status(1, &status) == 0 && status.last_phase == S2A_RUNTIME_GUEST_RUNNING) {
            s2a_host_shutdown(host->stop_reason.c_str());
            return nullptr;
        }
        usleep(10000);
    }
    __android_log_print(ANDROID_LOG_FATAL, "S2Arm", "Stop deadline during game initialization; no cleanup completion claimed");
    _exit(124);
}
